def add(cid, claim, ok, detail=''):
    checks.append((cid, claim, bool(ok), str(detail)[:500]))


def load(path):
    return V.load_json_strict(path)


def _guard(label, fn):
    try:
        return fn()
    except Exception as exc:
        CRASHES.append('%s: %s: %s' % (label, type(exc).__name__, exc))
        return _Broken()


def result(name):
    return _guard(name, lambda: V.validate_state(load(FIX / name), POLICY, SCHEMA))


def extra_result(name):
    return _guard(name, lambda: V.validate_state(load(EXTRAS / name), POLICY, SCHEMA))


def matched(rep, code, dimension=None, role=None, candidate=None, message=None):
    found = []
    for issue in rep.issues:
        if issue.code != code:
            continue
        if dimension is not None and issue.dimension != dimension:
            continue
        if role is not None and issue.role != role:
            continue
        if candidate is not None and issue.candidate != candidate:
            continue
        if message is not None and message not in issue.message:
            continue
        found.append(issue)
    return found


def has(rep, code, dimension=None, role=None, candidate=None, message=None):
    return bool(matched(rep, code, dimension, role, candidate, message))


def codes(rep):
    return ','.join(i.code for i in rep.issues) or '-'


def blocked(rep, code, **kw):
    """One check that requires both the diagnostic and no positive readiness."""
    ok = has(rep, code, **kw) and not rep.stage_b_role_ready
    detail = codes(rep) if ok else ('MISSING %s | %s | stage_b=%s' % (
        code, codes(rep), rep.stage_b_role_ready))
    return ok, detail


def raises(fn, exc_type, token):
    try:
        fn()
    except exc_type as exc:
        return (token in str(exc)), str(exc)
    except Exception as exc:  # wrong exception type is also a failure
        return False, '%s: %s' % (type(exc).__name__, exc)
    return False, 'NO EXCEPTION RAISED'


